    return provider(AppLocalizationKeys.sortByDefault);
  }

  /// Sort by Version
  String sortByVersion() {
    return provider(AppLocalizationKeys.sortByVersion);
  }

  /// Rewards
  String rewards() {
    return provider(AppLocalizationKeys.rewards);
  }
}

/// App localizations
final class AppLocalization {
  static AppLocalization of(BuildContext context) {
    final service = Localizations.of<AppLocalization>(context, AppLocalization);
    assert(
      service != null,
      'Make sure to add AppLocalization.createDelegate() to MaterialApp.',
    );
    return service!;
  }

  static LocalizationsDelegate<AppLocalization> createDelegate({
    required Map<Locale, String> assets,
    Locale? fallback,
  }) {
    return _AppLocalizationDelegate(assets, fallback);
  }

  final Map<String, String> _values;
  late final labels = AppLocalizationMethods(valueOf);
  AppLocalization._(this._values);

  String valueOf(String key, {int? howMany, Map<String, dynamic>? params}) {
    var value = howMany != null
        ? Intl.plural(
            howMany,
            zero: _values['$key.zero'],
            one: _values['$key.one'],
            two: _values['$key.two'],
            few: _values['$key.few'],
            many: _values['$key.many'],
            other: _values[key] ?? '',
          )
        : _values[key] ?? '';
    params?.forEach((k, v) => value = value.replaceAll('{$k}', '$v'));
    return value;
  }
}

class _AppLocalizationDelegate extends LocalizationsDelegate<AppLocalization> {
  final Locale? fallback;
  final Map<Locale, String> assets;
  _AppLocalizationDelegate(this.assets, this.fallback);

  @override
  Future<AppLocalization> load(Locale locale) async {
    final asset = assets[locale] ?? assets[fallback];
    if (asset == null) {
      throw Exception('Cannot load $locale');
    }

    final data = await rootBundle.loadString(asset);
    final map = (jsonDecode(data) as Map).cast<String, String>();
    return AppLocalization._(map);
  }

  @override
  bool isSupported(Locale locale) {
    return assets.containsKey(locale) || assets.containsKey(fallback);
  }

  @override
  bool shouldReload(covariant LocalizationsDelegate<AppLocalization> old) {
    if (old is! _AppLocalizationDelegate) return true;
    return kDebugMode ||
        fallback != old.fallback ||
        !mapEquals(assets, old.assets);
  }
}

extension AppLocalizationExt on BuildContext {
  AppLocalizationMethods get labels => AppLocalization.of(this).labels;
}
